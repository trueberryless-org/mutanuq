// Pages that are not listed in the sidebar (for example overview pages of subdirectories) still belong to a topic.
// The view modes of starlight-view-modes render every page a second time below /zen-mode/ and /presentation-mode/.
const modes = ["", "zen-mode/", "presentation-mode/"];

/** @param {string[]} directories */
function unlisted(...directories) {
  return directories.flatMap((directory) =>
    modes.map((mode) => `/*/${mode}${directory}/**`)
  );
}

